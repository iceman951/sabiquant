#!/usr/bin/env python3
"""Project the existing frozen HYBRID144 into self-contained Rust unit cases.

This fixes an extracted-package test dependency. It copies only existing
constructor literals, expected horizon bits and selected-branch facts; no
financial, date, horizon, threshold or oracle arithmetic is evaluated.
"""
import argparse
import csv
import hashlib
import io
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "validation/fixtures/bonds/enclosure-hybrid.fixture"
OUTPUT = ROOT / "src/bonds/enclosure/generic_hybrid_cases.rs"
SOURCE_SHA256 = "b74caa0280208a67858f04596decd7cb31c51b83b3b1e40ce933e65419794628"
COLUMNS = ("id method quote_frequency m threshold_bits threshold_bit_offset label "
           "issue settlement payment face_literal redemption_literal trial_yield_literal "
           "accrual_frequency accrual_events_per_year periods overlap_days reference_days "
           "exact_unrounded_horizon expected_horizon_bits expected_branch_from_adopted_rule "
           "expected_dirty_amount_bits expected_moment_and_macaulay_bits expected_entitled_flows "
           "expected_accrual_work neumaier_trace market_scope").split()


def require(condition, message):
    if not condition:
        raise ValueError(message)


def literal(value):
    require(value.isascii(), "Rust literal requires an ASCII source field")
    return json.dumps(value)


def period_literals(value):
    fields = {}
    for cell in value.split(";"):
        key, payload = cell.split("=", 1)
        require(key not in fields, "duplicate period path")
        fields[key] = payload
    require(fields.get("$") in ("l:1", "l:2"), "unexpected period cardinality")
    count = int(fields["$"][2:])
    require(len(fields) == 1 + 3 * count, "period shape changed")
    pairs = []
    for i in range(count):
        require(fields.get(f"[{i}]") == "l:2", "period pair shape changed")
        pair = []
        for side in range(2):
            date = fields.get(f"[{i}][{side}]", "")
            require(date.startswith("s:"), "period date tag changed")
            pair.append(literal(date[2:]))
        pairs.append("(" + ", ".join(pair) + ")")
    return "&[" + ", ".join(pairs) + "]"


def render():
    original = SOURCE.read_bytes()
    require(hashlib.sha256(original).hexdigest() == SOURCE_SHA256,
            "frozen HYBRID source bytes changed")
    _, table = original.decode("utf-8").split("\n\n", 1)
    reader = csv.DictReader(io.StringIO(table), delimiter="\t")
    require(reader.fieldnames == COLUMNS, "frozen HYBRID columns changed")
    rows = list(reader)
    require(len(rows) == 144, "HYBRID row count changed")
    out = [
        "//! Self-contained unit inputs projected from the same frozen HYBRID144.",
        "//! Generated by validation/generator/enclosure_hybrid_unit.py; no math/oracle.",
        f"//! Original FS1 SHA256: {SOURCE_SHA256}.",
        "", "#[derive(Debug)]", "pub(super) struct Case {",
    ]
    string_fields = ["id", "method", "quote_frequency", "accrual_frequency",
                     "issue", "settlement", "payment", "face_literal", "redemption_literal"]
    out.extend(f"    pub(super) {name}: &'static str," for name in string_fields)
    out.extend([
        "    pub(super) periods: &'static [(&'static str, &'static str)],",
        "    pub(super) expected_horizon_bits: u64,",
        "    pub(super) expected_branch: &'static str,",
        "    pub(super) m: Option<u32>,", "}", "",
        'pub(super) const SOURCE_SHA256: &str =',
        f'    "{SOURCE_SHA256}";', "",
        "#[rustfmt::skip]", "pub(super) const CASES: &[Case; 144] = &[",
    ])
    for i, row in enumerate(rows, 1):
        require(set(row) == set(COLUMNS) and None not in row.values(), "row shape changed")
        require(row["id"] == f"ICMA-REACH-{i:04}", "row identity/order changed")
        require(re.fullmatch("[0-9a-f]{16}", row["expected_horizon_bits"]), "horizon bits changed shape")
        require(row["m"] == "-" or re.fullmatch("[0-9]+", row["m"]), "m changed shape")
        require(row["expected_branch_from_adopted_rule"] in ("Simple", "Continuous", "Periodic"),
                "branch fact changed shape")
        out.append("    Case {")
        out.extend(f"        {name}: {literal(row[name])}," for name in string_fields)
        out.append(f"        periods: {period_literals(row['periods'])},")
        out.append(f"        expected_horizon_bits: 0x{row['expected_horizon_bits']},")
        out.append(f"        expected_branch: {literal(row['expected_branch_from_adopted_rule'])},")
        out.append("        m: " + ("None" if row["m"] == "-" else f"Some({row['m']})") + ",")
        out.append("    },")
    out.extend([
        "];", "",
    ])
    return ("\n".join(out)).encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check byte reproduction without writing")
    args = parser.parse_args()
    expected = render()
    if args.check:
        require(OUTPUT.read_bytes() == expected, "Rust unit projection bytes differ")
        action = "checked"
    else:
        with OUTPUT.open("xb") as output:
            output.write(expected)
        action = "created"
    print(f"{action} 144 unchanged HYBRID unit cases; SHA256 {hashlib.sha256(expected).hexdigest()}")


if __name__ == "__main__":
    main()
